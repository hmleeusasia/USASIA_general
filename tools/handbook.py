#!/usr/bin/env python3
"""Generate docs/handbook/code-map(.ko).md for this repo from the code, and check it is complete.

Usage:
  py tools/handbook.py          # rewrite docs/handbook/code-map.md and code-map.ko.md
  py tools/handbook.py --check  # exit 1 if a page is stale or a meaning is missing (pre-commit, session-end)

Sources (read only): tools/**/*.py (modules, functions, who calls them, local imports), tools/hooks/config.json
(rule modes), .claude/skills/*/SKILL.md (name, description, which tools/docs/skills each one uses),
docs/rules/*.md (rule IDs and where they are cited). Meanings: docs/handbook/meta.json (en + ko).
English meaning falls back to the function/module docstring; Korean must be in meta.json.
Never read: .claude/settings*.json (personal hook paths), CLAUDE.local.md, docs/users/** (personal).
"""
import ast, json, pathlib, re, sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
ROOT = pathlib.Path(__file__).resolve().parent.parent
HB = ROOT / "docs/handbook"
META = HB / "meta.json"
HEADER = "<!-- GENERATED by tools/handbook.py from the code. Do not edit; edit the code or docs/handbook/meta.json. -->\n"
SENSITIVE = {"email address": re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}"),
             "IP address": re.compile(r"(?<![\d.])(?:\d{1,3}\.){3}\d{1,3}(?![\d.])"),
             "host name": re.compile(r"\b[\w-]+(?:\.[\w-]+)*\.(?:duckdns\.org|com|net|org|io|cloud)\b"),
             "server path": re.compile(r"/srv/[\w/.-]+|/root/[\w/.-]+")}
HOST_OK = {"claude.com", "github.com", "healthchecks.io"}  # public sites that may be named


def rel(p):
    return p.relative_to(ROOT).as_posix()


def py_files():
    return [p for p in sorted((ROOT / "tools").rglob("*.py")) if "__pycache__" not in p.parts]


def first_line(doc):
    return (doc or "").strip().splitlines()[0] if doc else ""


def parse_modules():
    """{path: {"doc", "functions": [{name, line, args, doc}], "imports": [local module names], "calls": set}}"""
    mods = {}
    for p in py_files():
        tree = ast.parse(p.read_text(encoding="utf-8"))
        funcs = [{"name": n.name, "line": n.lineno, "args": [a.arg for a in n.args.args],
                  "doc": first_line(ast.get_docstring(n))}
                 for n in tree.body if isinstance(n, ast.FunctionDef)]
        imports, calls = set(), set()
        for n in ast.walk(tree):
            if isinstance(n, ast.Import):
                imports |= {a.name.split(".")[0] for a in n.names}
            elif isinstance(n, ast.ImportFrom) and n.module:
                imports.add(n.module.split(".")[0])
            elif isinstance(n, ast.Call):
                f = n.func
                calls.add(f.id if isinstance(f, ast.Name) else f.attr if isinstance(f, ast.Attribute) else "")
        mods[rel(p)] = {"doc": first_line(ast.get_docstring(tree)), "functions": funcs,
                        "imports": imports, "calls": calls, "text": p.read_text(encoding="utf-8")}
    local = {pathlib.Path(k).stem: k for k in mods}
    for k, m in mods.items():
        m["local_imports"] = sorted(local[i] for i in m["imports"] if i in local and local[i] != k)
        # scripts run by name (e.g. launch.sh digest.py, subprocess calls) count as uses too
        # only short string constants (paths, commands) count, not comments or docstrings
        consts = [n.value for n in ast.walk(ast.parse(m["text"]))
                  if isinstance(n, ast.Constant) and isinstance(n.value, str) and len(n.value) < 120]
        m["runs"] = sorted(v for s, v in local.items() if v != k and any(re.search(rf"\b{re.escape(s)}\.py\b", c) for c in consts))
    return mods


def callers(mods, path, fname):
    stem = pathlib.Path(path).stem
    out = []
    for k, m in mods.items():
        if k == path:
            if sum(1 for f in m["functions"] if f["name"] == fname) and re.search(rf"(?<![\w.]){re.escape(fname)}\(", m["text"].split(f"def {fname}(", 1)[0] + m["text"].split(f"def {fname}(", 1)[-1].split("\n", 1)[-1]):
                out.append("(same file)")
        elif fname in m["calls"] and (stem in m["imports"] or re.search(rf"\b{stem}\.{re.escape(fname)}\b", m["text"])):
            out.append(k)
    return out


def parse_skills():
    out = []
    for p in sorted((ROOT / ".claude/skills").glob("*/SKILL.md")):
        text = p.read_text(encoding="utf-8")
        name = re.search(r"^name:\s*(.+)$", text, re.M)
        desc = re.search(r"^description:\s*(.+)$", text, re.M)
        uses_tools = sorted(set(re.findall(r"tools/[\w/]+\.(?:py|sh|js)", text)))
        uses_docs = sorted(set(re.findall(r"docs/(?:rules|kb)/[\w.-]+\.md", text)))
        uses_skills = sorted({s for s in re.findall(r"\b([a-z]+(?:-[a-z]+)+|todo)\b skill", text)} - {p.parent.name})
        rules = sorted(set(re.findall(r"R-[A-Z]+-\d+", text)))
        out.append({"dir": p.parent.name, "name": name.group(1).strip() if name else p.parent.name,
                    "desc": desc.group(1).strip() if desc else "", "tools": uses_tools, "docs": uses_docs,
                    "skills": uses_skills, "rules": rules})
    return out


def parse_rules():
    """{rule_id: (file, title)} from docs/rules/*.md '## R-XXX-NN' headings."""
    out = {}
    for p in sorted((ROOT / "docs/rules").glob("*.md")):
        for m in re.finditer(r"^## (R-[A-Z]+-\d+)\s*(.*)$", p.read_text(encoding="utf-8"), re.M):
            out[m.group(1)] = (rel(p), m.group(2).strip())
    return out


def rule_citations(rule_id):
    hits = []
    for p in sorted(list((ROOT / "tools").rglob("*.py")) + list((ROOT / "tools").rglob("*.json"))
                    + list((ROOT / ".claude/skills").rglob("*.md"))):
        if "__pycache__" in p.parts:
            continue
        if re.search(rf"\b{re.escape(rule_id)}\b", p.read_text(encoding="utf-8")):
            hits.append(rel(p))
    return hits


L = {
    "en": {"t": "Code map (USASIA_general)", "other": "Other language: ", "mods": "Python tools and hooks",
           "fn": "Function", "line": "Line", "args": "Arguments", "mean": "Meaning", "calls": "Called from",
           "imports": "Imports local modules", "runs": "Mentions/runs scripts", "modes": "Hook rule modes (tools/hooks/config.json)",
           "rule": "Rule", "mode": "Mode", "id": "Rule ID", "skills": "Skills", "skill": "Skill", "desc": "Description",
           "ut": "Uses tools", "ud": "Reads rule/kb files", "us": "Calls skills", "rules": "Rules (docs/rules) and where they are enforced or cited",
           "title": "Title", "cited": "Cited in code/skills", "none": "—", "missing": "**(missing)**"},
    "ko": {"t": "코드 지도 (USASIA_general)", "other": "다른 언어: ", "mods": "Python 도구와 hook",
           "fn": "함수", "line": "줄", "args": "인자", "mean": "의미", "calls": "부르는 곳",
           "imports": "가져오는 내부 모듈", "runs": "언급하거나 실행하는 스크립트", "modes": "Hook 규칙 모드 (tools/hooks/config.json)",
           "rule": "규칙", "mode": "모드", "id": "규칙 ID", "skills": "Skill", "skill": "Skill", "desc": "설명",
           "ut": "쓰는 도구", "ud": "읽는 규칙·kb 파일", "us": "부르는 skill", "rules": "규칙(docs/rules)과 그것을 지키거나 인용하는 곳",
           "title": "제목", "cited": "인용한 코드·skill", "none": "—", "missing": "**(없음)**"},
}


def meaning(meta_entry, lang, fallback=""):
    v = (meta_entry or {}).get(lang) or (fallback if lang == "en" else "")
    return v or L[lang]["missing"]


def render(mods, skills, rules, meta, lang):
    t = L[lang]
    other = "code-map.md" if lang == "ko" else "code-map.ko.md"
    out = [HEADER, f"# {t['t']}\n", f"{t['other']}[{other}]({other})\n", f"## {t['mods']}\n"]
    for path, m in mods.items():
        out.append(f"### `{path}`\n\n{meaning(meta['modules'].get(path), lang, m['doc'])}\n")
        out.append(f"- {t['imports']}: {', '.join(f'`{x}`' for x in m['local_imports']) or t['none']}")
        out.append(f"- {t['runs']}: {', '.join(f'`{x}`' for x in m['runs']) or t['none']}")
        if m["functions"]:
            out.append(f"\n| {t['fn']} | {t['line']} | {t['args']} | {t['mean']} | {t['calls']} |\n|---|---|---|---|---|")
            for f in m["functions"]:
                key = f"{path}#{f['name']}"
                out.append(f"| `{f['name']}` | {f['line']} | {', '.join(f['args']) or t['none']} | "
                           f"{meaning(meta['functions'].get(key), lang, f['doc'])} | {', '.join(callers(mods, path, f['name'])) or t['none']} |")
        out.append("")
    cfg = json.loads((ROOT / "tools/hooks/config.json").read_text(encoding="utf-8"))
    out.append(f"## {t['modes']}\n\n| {t['rule']} | {t['mode']} | {t['id']} |\n|---|---|---|")
    out += [f"| `{r}` | {mode} | {cfg.get('ids', {}).get(r, t['none'])} |" for r, mode in cfg["rules"].items()]
    out.append(f"\n## {t['skills']}\n\n| {t['skill']} | {t['desc']} | {t['ut']} | {t['ud']} | {t['us']} |\n|---|---|---|---|---|")
    for s in skills:
        d = meaning(meta["skills"].get(s["dir"]), lang)
        out.append(f"| `{s['dir']}` | {d} | {', '.join(s['tools']) or t['none']} | {', '.join(s['docs']) or t['none']} | {', '.join(s['skills']) or t['none']} |")
    out.append(f"\n## {t['rules']}\n\n| {t['id']} | {t['title']} | {t['cited']} |\n|---|---|---|")
    for rid, (f, title) in rules.items():
        out.append(f"| {rid} ({f}) | {title or t['none']} | {', '.join(rule_citations(rid)) or t['none']} |")
    return "\n".join(out) + "\n"


def check_meta(mods, skills, meta):
    errs = []
    for path, m in mods.items():
        if not meta["modules"].get(path, {}).get("ko"):
            errs.append(f"meta.json: module {path} has no 'ko' meaning")
        if not (m["doc"] or meta["modules"].get(path, {}).get("en")):
            errs.append(f"{path}: add a module docstring or an 'en' meaning in meta.json")
        for f in m["functions"]:
            key = f"{path}#{f['name']}"
            e = meta["functions"].get(key, {})
            if not (f["doc"] or e.get("en")):
                errs.append(f"{path}:{f['line']} {f['name']}: add a docstring or an 'en' meaning in meta.json")
            if not e.get("ko"):
                errs.append(f"meta.json: function {key} has no 'ko' meaning")
    for s in skills:
        for lang in ("en", "ko"):
            if not meta["skills"].get(s["dir"], {}).get(lang):
                errs.append(f"meta.json: skill {s['dir']} has no '{lang}' meaning")
    # stale meanings: keys whose module, function or skill no longer exists
    funcs = {f"{p}#{f['name']}" for p, m in mods.items() for f in m["functions"]}
    errs += [f"meta.json: module {k} no longer exists; remove it" for k in meta["modules"] if k not in mods]
    errs += [f"meta.json: function {k} no longer exists; remove it" for k in meta["functions"] if k not in funcs]
    errs += [f"meta.json: skill {k} no longer exists; remove it" for k in meta["skills"] if k not in {s["dir"] for s in skills}]
    return errs


def main():
    meta = json.loads(META.read_text(encoding="utf-8")) if META.exists() else {}
    for k in ("modules", "functions", "skills"):
        meta.setdefault(k, {})
    mods, skills, rules = parse_modules(), parse_skills(), parse_rules()
    outputs = {HB / "code-map.md": render(mods, skills, rules, meta, "en"),
               HB / "code-map.ko.md": render(mods, skills, rules, meta, "ko")}
    errs = check_meta(mods, skills, meta)
    pages = [(p, p.read_text(encoding="utf-8")) for p in sorted(HB.glob("*.md")) if p not in outputs]
    for p, text in list(outputs.items()) + pages + [(META, META.read_text(encoding="utf-8") if META.exists() else "")]:
        for label, pat in SENSITIVE.items():
            for hit in pat.findall(text):
                if not (label == "IP address" and hit.startswith(("0.", "127.", "1."))) and hit not in HOST_OK:
                    errs.append(f"{rel(p)}: looks like an {label} ({hit[:3]}...); keep it out")
    if "--check" in sys.argv:
        for p, text in outputs.items():
            if not p.exists() or p.read_text(encoding="utf-8") != text:
                errs.append(f"{rel(p)} is stale: run py tools/handbook.py and commit")
    else:
        HB.mkdir(parents=True, exist_ok=True)
        for p, text in outputs.items():
            p.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {', '.join(rel(p) for p in outputs)}")
    for e in errs:
        print("handbook:", e)
    sys.exit(1 if errs else 0)


if __name__ == "__main__":
    main()
